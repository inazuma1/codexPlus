import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import net from 'node:net';

test('HTTP 双向交互：鉴权、SSE、等待时并行处理、答案校验和取消',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'codexplus-interactive-'));
  const probe=net.createServer();await new Promise(r=>probe.listen(0,'127.0.0.1',r));const port=probe.address().port;await new Promise(r=>probe.close(r));
  const base=`http://127.0.0.1:${port}`;
  const child=spawn(process.execPath,['src/server.js'],{env:{...process.env,PORT:String(port),HOST:'127.0.0.1',DATA_DIR:dir,ADMIN_TOKEN:'admin',WEBHOOK_TOKEN:'hook',MOCK_CODEX:'false',CODEX_BIN:process.execPath,CODEX_WORKDIR:dir,CODEX_TIMEOUT_MS:'2000',NODE_OPTIONS:`--import=${new URL('./fixture-preload.js',import.meta.url).href}`},stdio:['ignore','pipe','pipe']});
  let log='';child.stderr.on('data',s=>log+=s);
  t.after(async()=>{if(child.exitCode===null){const end=new Promise(r=>child.once('exit',r));child.kill();await end;}rmSync(dir,{recursive:true,force:true});});
  async function until(fn){for(let i=0;i<150;i++){try{const v=await fn();if(v)return v;}catch{}await new Promise(r=>setTimeout(r,30));}throw new Error('等待超时 '+log);}
  await until(()=>fetch(base+'/healthz').then(r=>r.ok));
  const req=(path,body,token='admin',method)=>fetch(base+path,{method:method||(body===undefined?'GET':'POST'),headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});
  const state=async()=>await(await req('/api/state')).json();
  const s=await(await req('/api/sessions',{title:'问答'})).json();
  await req(`/api/sessions/${s.id}/messages`,{content:'ask'});
  const pending=await until(async()=>{const v=await state();return v.requests[0]&&v;});
  const r=pending.requests[0];assert.equal(pending.jobs[0].status,'waiting');
  assert.equal((await req(`/api/sessions/${s.id}`,undefined,'admin','DELETE')).status,409);
  assert.equal((await req(`/api/sessions/${s.id}`,{title:'忙碌时重命名'},'admin','PATCH')).status,409);
  assert.equal((await req(`/api/interactions/${r.id}/respond`,{answers:{answer:'测试'}},'hook')).status,401);
  assert.equal((await req(`/api/interactions/${r.id}/respond`,{})).status,400);
  const stream=await req('/api/events'),reader=stream.body.getReader();
  assert.match(stream.headers.get('content-type'),/event-stream/);
  assert.match(new TextDecoder().decode((await reader.read()).value),/需要你的回答/);await reader.cancel();
  const s2=await(await req('/api/sessions',{title:'并行'})).json();
  await req(`/api/sessions/${s2.id}/messages`,{content:'hello'});
  await until(async()=>(await state()).jobs.find(j=>j.session_id===s2.id)?.status==='done');
  assert.equal((await req(`/api/interactions/${r.id}/respond`,{answers:{answer:'测试'}})).status,200);
  assert.equal((await req(`/api/interactions/${r.id}/respond`,{answers:{answer:'测试'}})).status,409);
  await until(async()=>(await state()).jobs.find(j=>j.session_id===s.id)?.status==='done');
  const approvalPath=`/api/sessions/${s.id}/approval`;
  assert.equal((await req(approvalPath,{autoApprove:true},'hook','PATCH')).status,401);
  assert.equal((await req(approvalPath,{autoApprove:'true'},'admin','PATCH')).status,400);
  assert.equal((await req('/api/sessions/missing/approval',{autoApprove:true},'admin','PATCH')).status,404);
  assert.equal((await state()).sessions.find(row=>row.id===s.id).auto_approve,false);
  assert.equal((await req(approvalPath,{autoApprove:true},'admin','PATCH')).status,200);
  for(const content of ['approve','approve-file','permission']) {
    const queued=await(await req(`/api/sessions/${s.id}/messages`,{content})).json();
    await until(async()=>(await state()).jobs.find(j=>j.id===queued.jobId)?.status==='done');
    const messages=await(await req(`/api/sessions/${s.id}/messages`)).json();
    assert.match(messages.at(-1).content,content==='permission'?/"scope":"turn"/:/"decision":"accept"/);
    assert.ok(messages.some(m=>m.content.includes('[自动审批]')));
  }
  await req(`/api/sessions/${s.id}/messages`,{content:'ask'});
  const question=await until(async()=>(await state()).requests.find(r=>r.session_id===s.id));
  assert.equal(question.kind,'question');
  await req(`/api/interactions/${question.id}/respond`,{answers:{answer:'仍然需要回答'}});
  await until(async()=>(await state()).jobs.find(j=>j.id===question.job_id)?.status==='done');
  await req(`/api/sessions/${s2.id}/messages`,{content:'approve'});
  const isolated=await until(async()=>(await state()).requests.find(r=>r.session_id===s2.id));
  assert.equal(isolated.kind,'approval');
  await req(`/api/interactions/${isolated.id}/respond`,{decision:'decline'});
  await until(async()=>(await state()).jobs.find(j=>j.id===isolated.job_id)?.status==='done');
  await req(approvalPath,{autoApprove:false},'admin','PATCH');
  await req(`/api/sessions/${s.id}/messages`,{content:'approve'});
  const waitingApproval=await until(async()=>(await state()).requests.find(r=>r.session_id===s.id));
  assert.equal(waitingApproval.kind,'approval');
  const enabled=await(await req(approvalPath,{autoApprove:true},'admin','PATCH')).json();
  assert.equal(enabled.approved,1);
  assert.equal((await req(`/api/interactions/${waitingApproval.id}/respond`,{decision:'decline'})).status,409);
  await until(async()=>(await state()).jobs.find(j=>j.id===waitingApproval.job_id)?.status==='done');
  await req(approvalPath,{autoApprove:false},'admin','PATCH');
  await req(`/api/sessions/${s.id}/messages`,{content:'approve'});
  const approval=await until(async()=>(await state()).requests.find(r=>r.kind==='approval'));
  assert.equal((await req(`/api/interactions/${approval.id}/respond`,{decision:'decline'})).status,200);
  await until(async()=>(await state()).jobs.find(j=>j.session_id===s.id)?.status==='done');
  await req(`/api/sessions/${s.id}/messages`,{content:'ask'});
  const cancel=await until(async()=>(await state()).requests[0]);
  assert.equal((await req(`/api/jobs/${cancel.job_id}/cancel`,{})).status,200);
  await until(async()=>{const s=await state();return !s.requests.length&&s.jobs.find(j=>j.id===cancel.job_id).status==='failed';});
  const plan=await(await req('/api/sessions',{title:'计划',mode:'plan'})).json();
  await req(`/api/sessions/${plan.id}/messages`,{content:'hello'});
  await until(async()=>(await state()).jobs.find(j=>j.session_id===plan.id)?.status==='done');
  const planMessages=await(await req(`/api/sessions/${plan.id}/messages`)).json();assert.match(planMessages.at(-1).content,/PLAN:/);
  await req(`/api/sessions/${plan.id}/approval`,{autoApprove:true},'admin','PATCH');
  await req(`/api/sessions/${plan.id}/messages`,{content:'approve'});
  const planApproval=await until(async()=>(await state()).requests.find(r=>r.session_id===plan.id));
  assert.equal(planApproval.kind,'approval');
  assert.equal((await(await req(`/api/sessions/${plan.id}/approval`,{autoApprove:true},'admin','PATCH')).json()).approved,0);
  await req(`/api/interactions/${planApproval.id}/respond`,{decision:'decline'});
  await until(async()=>(await state()).jobs.find(j=>j.id===planApproval.job_id)?.status==='done');
  assert.equal((await req(`/api/sessions/${plan.id}`,{title:'原生会话同步标题'},'admin','PATCH')).status,200);
  assert.equal((await state()).sessions.find(s=>s.id===plan.id).title,'原生会话同步标题');
  assert.equal((await req(`/api/sessions/${plan.id}`,{mode:'default'},'admin','PATCH')).status,200);
  const g=await(await req('/api/sessions',{title:'自动目标'})).json();
  assert.equal((await req(`/api/sessions/${g.id}/goal`,{action:'start',objective:'work',tokenBudget:4000,maxTurns:2})).status,200);
  const finished=await until(async()=>{const v=await state(),s=v.sessions.find(s=>s.id===g.id);return s.goal?.status==='paused'&&s.goalConfig.turns===2&&v;});
  assert.equal(finished.jobs.filter(j=>j.session_id===g.id).length,2);
  assert.equal((await req(`/api/sessions/${g.id}/goal`,{action:'start',objective:'ask',tokenBudget:4000,maxTurns:2})).status,200);
  await until(async()=>(await state()).requests.some(r=>r.session_id===g.id));
  assert.equal((await req(`/api/sessions/${g.id}/goal`,{action:'pause'})).status,200);
  await until(async()=>{const v=await state();return v.sessions.find(s=>s.id===g.id).goal.status==='paused'&&!v.requests.some(r=>r.session_id===g.id)&&v.jobs.filter(j=>j.session_id===g.id).every(j=>!['running','waiting'].includes(j.status));});
  assert.equal((await req(`/api/sessions/${g.id}/goal`,{action:'resume'})).status,200);
  await until(async()=>(await state()).requests.some(r=>r.session_id===g.id));
  assert.equal((await req(`/api/sessions/${g.id}/goal`,{action:'clear'})).status,200);
  await until(async()=>{const v=await state();return !v.sessions.find(s=>s.id===g.id).goal&&v.jobs.filter(j=>j.session_id===g.id).every(j=>!['running','waiting'].includes(j.status));});
  assert.equal((await req(`/api/sessions/${g.id}`,undefined,'hook','DELETE')).status,401);
  assert.equal((await req(`/api/sessions/${g.id}`,undefined,'admin','DELETE')).status,200);
  const deleted=await state();assert.ok(!deleted.sessions.some(s=>s.id===g.id));assert.ok(!deleted.jobs.some(j=>j.session_id===g.id));
  assert.equal((await req(`/api/sessions/${g.id}/messages`)).status,404);
});
